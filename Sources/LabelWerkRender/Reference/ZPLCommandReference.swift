import Foundation

/// Nachschlagewerk der ZPL-II-Befehle für Terminal-Autovervollständigung und Hilfe.
///
/// `command` enthält das Präfix (`"^FO"`, `"~DG"`); Befehle, die es mit beiden Präfixen gibt,
/// erscheinen zweimal. `syntax` ist die Parameterschreibweise des ZPL II Programming Guide und
/// kann direkt als Vorlage eingefügt werden.
public enum ZPLCommandReference {

    public struct Entry: Hashable, Sendable {
        /// Befehl mit Präfix, z. B. `"^FO"`.
        public var command: String
        /// Deutscher Name.
        public var name: String
        /// Syntax mit Parameterplatzhaltern, z. B. `"^FOx,y,z"`.
        public var syntax: String
        /// Deutsche Kurzbeschreibung (ein Satz).
        public var summary: String

        public init(command: String, name: String, syntax: String, summary: String) {
            self.command = command
            self.name = name
            self.syntax = syntax
            self.summary = summary
        }
    }

    /// Alle Einträge, alphabetisch nach Befehl (Formatbefehle `^` vor Steuerbefehlen `~`).
    public static let entries: [Entry] = rawEntries
        .map { Entry(command: $0.0, name: $0.1, syntax: $0.2, summary: $0.3) }
        .sorted { lhs, rhs in
            if lhs.command.first != rhs.command.first { return lhs.command.first == "^" }
            return lhs.command < rhs.command
        }

    private static let index: [String: Entry] = Dictionary(entries.map { ($0.command, $0) },
                                                           uniquingKeysWith: { first, _ in first })

    /// Sucht den Eintrag zu einer Eingabe wie `"^FO"`, `"fo"`, `"^FO50,50"`, `"^A0N,30"`, `"~hqes"`.
    ///
    /// Ohne Präfix wird zuerst `^`, dann `~` versucht. `^A` mit Schriftbezeichner liefert `^A`
    /// (bzw. `^A@` für Schriftdateien).
    public static func lookup(_ command: String) -> Entry? {
        let trimmed = command.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let first = trimmed.first else { return nil }
        let prefixes: [Character]
        let body: Substring
        if first == "^" || first == "~" {
            prefixes = [first]
            body = trimmed.dropFirst()
        } else {
            prefixes = ["^", "~"]
            body = Substring(trimmed)
        }
        let code = String(body.prefix(2)).uppercased()
        for prefix in prefixes {
            if prefix == "^", code.first == "A" {
                if code == "A@", let entry = index["^A@"] { return entry }
                if let entry = index["^A"] { return entry }
            }
            if let entry = index["\(prefix)\(code)"] { return entry }
        }
        return nil
    }

    /// Einträge, deren Befehl mit `prefix` beginnt (ohne Groß-/Kleinschreibung), z. B. für die
    /// Autovervollständigung von `"^F"`.
    public static func completions(for prefix: String) -> [Entry] {
        let needle = prefix.uppercased()
        return entries.filter { $0.command.uppercased().hasPrefix(needle) }
    }

